import { describe, expect, it } from "vitest";
import { checkPart1, type CheckMode } from "./mock-exam-part1-checker";
import { checkPart1Answer } from "../../../src/lib/mockExamPart1Checker";

/**
 * Тесты на ЧЕКЕР ЧАСТИ 1 пробников — и одновременно на ПАРИТЕТ двух зеркал.
 *
 * Почему это второй по важности объект после балла ДЗ: чекер ставит балл за
 * экзамен молча и необратимо. Ошибка не падает — ученик просто получает не тот
 * результат, а репетитор по нему судит о готовности. Задокументированный симптом
 * дрейфа зеркал: «превью говорит верно, финал даёт 0».
 *
 * КАЖДЫЙ кейс здесь прогоняется через ОБА зеркала:
 *   • `supabase/functions/_shared/mock-exam-part1-checker.ts` — финальный балл;
 *   • `src/lib/mockExamPart1Checker.ts` — превью у репетитора.
 * Существующий `scripts/test-mockexam-checkmode-parity.mjs` (smoke §15) сверяет
 * структуру и ~10 пар; здесь проверяется СЕМАНТИКА режимов — те правила ФИПИ,
 * которые из кода не следуют и разъезжаются незаметно.
 */

/** Прогоняет вход через оба зеркала и требует одинакового результата. */
function grade(
  correct: string,
  student: string | null,
  mode: CheckMode,
  maxScore: number,
): number {
  const deno = checkPart1(correct, student, mode, maxScore);
  const front = checkPart1Answer({
    correctAnswer: correct,
    studentAnswer: student,
    checkMode: mode as never,
    maxScore,
  });

  // Расхождение зеркал — самостоятельный дефект, даже если оба «похожи на
  // правду». Сообщаем его отдельно от ожидаемого значения, иначе в отчёте
  // будет видно только «ожидали 2, получили 1», а не факт дрейфа.
  expect(
    { earned: front.earnedScore, correct: front.isCorrect },
    `ДРЕЙФ ЗЕРКАЛ [${mode}] эталон="${correct}" ответ="${student}": ` +
      `фронт ${front.earnedScore}, Deno ${deno.earned}`,
  ).toEqual({ earned: deno.earned, correct: deno.correct });

  return deno.earned;
}

describe("multi_choice против multi_choice_strict — у предметов РАЗНЫЕ критерии", () => {
  // Это главная пара тестов файла. Оба режима смотрят на множество цифр, но
  // ЗАМЕНУ цифры физика прощает, а обществознание — нет (критерии Милады,
  // 2026-07-23). Перепутать их местами = молча занизить или завысить экзамен
  // целому предмету, и никакая ошибка при этом не возникнет.

  it("замена цифры: физика даёт 1 балл, обществознание — 0", () => {
    // Эталон 123, ученик написал 124: одна цифра лишняя, одна недостающая.
    expect(grade("123", "124", "multi_choice", 2)).toBe(1);
    expect(grade("123", "124", "multi_choice_strict", 2)).toBe(0);
  });

  it("один недостающий ответ: оба режима дают 1 балл", () => {
    expect(grade("123", "12", "multi_choice", 2)).toBe(1);
    expect(grade("123", "12", "multi_choice_strict", 2)).toBe(1);
  });

  it("один лишний ответ: оба режима дают 1 балл", () => {
    expect(grade("12", "123", "multi_choice", 2)).toBe(1);
    expect(grade("12", "123", "multi_choice_strict", 2)).toBe(1);
  });

  it("полное совпадение — максимум, порядок не важен", () => {
    expect(grade("123", "321", "multi_choice", 2)).toBe(2);
    expect(grade("123", "321", "multi_choice_strict", 2)).toBe(2);
  });

  it("две ошибки — ноль в обоих", () => {
    expect(grade("123", "145", "multi_choice", 2)).toBe(0);
    expect(grade("123", "145", "multi_choice_strict", 2)).toBe(0);
  });

  it("частичный балл НЕ выдаётся, когда максимум = 1", () => {
    // Половины балла не бывает: при max_score=1 одна ошибка это ноль.
    expect(grade("123", "12", "multi_choice", 1)).toBe(0);
    expect(grade("123", "124", "multi_choice_strict", 1)).toBe(0);
  });
});

describe("ordered против ordered_lenient — Хэмминг против Левенштейна", () => {
  // `ordered` (физика): позиции сравниваются попарно, разная длина → сразу 0.
  // `ordered_lenient` (обществознание): вставка/удаление стоит одну ошибку,
  // поэтому пропущенная цифра ещё даёт балл, а вот перестановка (две правки) —
  // уже нет.

  it("одна неверная позиция — 1 балл в обоих режимах", () => {
    expect(grade("123", "124", "ordered", 2)).toBe(1);
    expect(grade("123", "124", "ordered_lenient", 2)).toBe(1);
  });

  it("недостающая позиция: строгий режим даёт 0, мягкий — 1", () => {
    // Ровно то, ради чего заведён lenient: у обществознания короткий ответ
    // считается одной ошибкой, а не браком.
    expect(grade("123", "12", "ordered", 2)).toBe(0);
    expect(grade("123", "12", "ordered_lenient", 2)).toBe(1);
  });

  it("транспозиция соседних цифр даёт 0 даже в мягком режиме", () => {
    // Перестановка — это ДВЕ правки по Левенштейну. Соблазн засчитать её за
    // одну ошибку велик, но критерии ФИПИ так не считают.
    expect(grade("1234", "1243", "ordered_lenient", 2)).toBe(0);
  });

  it("разделители не влияют на результат", () => {
    expect(grade("1,2,3", "123", "ordered", 2)).toBe(2);
    expect(grade("1;2;3", "1, 2, 3", "ordered_lenient", 2)).toBe(2);
  });
});

describe("strict — точное совпадение и допуск округления", () => {
  it("запятая и точка в десятичной дроби равнозначны", () => {
    expect(grade("5.6", "5,6", "strict", 1)).toBe(1);
  });

  it("округление до знаков эталона засчитывается", () => {
    // Эталон с одним знаком после запятой — ученик, посчитавший точнее,
    // не должен получить ноль.
    expect(grade("0.5", "0.50", "strict", 1)).toBe(1);
  });

  it("другое число — ноль", () => {
    expect(grade("5.6", "5.7", "strict", 1)).toBe(0);
  });

  it("допуск округления НЕ распространяется на другие режимы", () => {
    // Он намеренно живёт только в strict: в ordered «5,6» и «56» — разные
    // последовательности, а не одно число.
    expect(grade("56", "5.6", "ordered", 2)).toBe(0);
  });
});

describe("task20 — «выберите два номера», порядок не важен", () => {
  it("«13» и «31» — один и тот же ответ", () => {
    expect(grade("13", "31", "task20", 1)).toBe(1);
  });

  it("дубликат цифры не проходит", () => {
    // Регресс 2026-06-07 был обратным (строковое равенство), поэтому проверяем
    // обе стороны: перестановка засчитывается, а «133» вместо «13» — нет.
    expect(grade("13", "133", "task20", 1)).toBe(0);
  });

  it("нецифровой ответ — ноль", () => {
    expect(grade("13", "1a", "task20", 1)).toBe(0);
  });
});

describe("общие правила, действующие во всех режимах", () => {
  const modes: CheckMode[] = [
    "strict",
    "ordered",
    "ordered_lenient",
    "unordered",
    "multi_choice",
    "multi_choice_strict",
    "task20",
    "pair",
  ];

  it("пустой ответ ученика — всегда ноль", () => {
    for (const mode of modes) {
      expect(grade("123", "", mode, 2), `режим ${mode}`).toBe(0);
      expect(grade("123", null, mode, 2), `режим ${mode}`).toBe(0);
      expect(grade("123", "   ", mode, 2), `режим ${mode}`).toBe(0);
    }
  });

  it("режим manual не проверяется автоматически — это Часть 2", () => {
    // Если бы manual вдруг начал что-то считать, развёрнутые ответы получали
    // бы автоматический балл в обход репетитора.
    expect(grade("123", "123", "manual", 3)).toBe(0);
  });

  it("верный ответ даёт РОВНО максимум, а не единицу", () => {
    // Защита от подмены `maxScore` на литерал 1: у Части 1 бывают двухбалльные
    // задания, и потолок обязан следовать из данных задачи.
    expect(grade("123", "123", "multi_choice", 2)).toBe(2);
    expect(grade("123", "123", "ordered", 3)).toBe(3);
  });
});
