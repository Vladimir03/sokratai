-- одного типа с одинаковым (без регистра/пробелов) именем.
--
-- Инцидент Дианы Шевцовой 2026-07-27: два «11 класс» (создание из карточки
-- ученика, Select не показал свежую группу из-за медленного рефетча под RU-DPI →
-- повторное создание через 5 минут). App-уровень теперь делает create-or-reuse
-- (src/lib/tutors.ts::createTutorGroup), индекс — страховка от гонок.
-- Прод-срез перед накаткой: единственный дубль (Дианин) заархивирован вручную.
--
-- Partial (WHERE is_active): архивные имена не блокируют пересоздание группы
-- с тем же названием.

CREATE UNIQUE INDEX IF NOT EXISTS tutor_groups_unique_active_name
  ON public.tutor_groups (tutor_id, is_primary, (lower(trim(name))))
  WHERE is_active = true;
