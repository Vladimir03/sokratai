--
-- ПРИЧИНА. В `kb_topics` для `maths` было 5 тем против 42 у физики, и
-- `topic_suggestion → topic_id` резолвится ТОЧНЫМ совпадением имени. Итог на
-- живых данных: у репетитора-математика Павла Иванова 101 задача из 121 легла
-- БЕЗ темы — его база превратилась в плоский список без фильтров и навигации.
--
-- ИСТОЧНИКИ. Названия тем — официальная разбивка ОГЭ (скриншоты ФИПИ-структуры
-- от владельца 2026-08-07: «Задания 1–19 с кратким ответом» + «Задания 20–25 с
-- развёрнутым ответом»). Подтемы — тематический классификатор РЕШУ ОГЭ
-- (math-oge.sdamgia.ru), его нумерация заданий совпадает с официальной
-- один-в-один. Подтемы НЕ выдуманы.
--
-- Модель — зеркало физики (`20260312120001_kb_seed_physics`): имя темы БЕЗ
-- номера (номера живут в `kim_numbers`), `section` = крупный блок, `exam='oge'`,
-- `kind='exam'`. Имя без номера принципиально: по нему матчится AI-загрузчик,
-- и «Треугольник» он предложит, а «15. Треугольник» — нет.
--
-- ⚠️ АДДИТИВНО. Пять существующих тем `maths` НЕ трогаем — в них лежит 1127
-- задач живых репетиторов, и часть из них перекрывается с новыми по № КИМ
-- («Треугольники» kim=15 ↔ «Треугольник», «Вероятность и статистика» kim=10 ↔
-- «Теория вероятностей», «Алгебра» kim=6, «Алгебра ОГЭ» kim=14). Переносить
-- чужие задачи миграцией нельзя: это продуктовое решение владельца и
-- репетиторов, а не следствие сидирования. Слияние — отдельным шагом ПОСЛЕ
-- согласования, см. `docs/delivery/features/kb-maths-taxonomy/spec.md`.
--
-- Идемпотентно: уникального индекса на (subject, exam, name) нет, поэтому
-- вставка идёт через NOT EXISTS — повторный прогон не создаст дублей.
-- ============================================================================

